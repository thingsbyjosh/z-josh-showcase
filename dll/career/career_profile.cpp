// Letter-band display table (mirrors data_career.jsx RATING_BANDS, anchored to RATING_BAND_MIN).
// idx 5=A .. 0=F, plus a synthetic "S" above A for the Legend look (score >= A_min + 400).
static RatingBandView BandView(int score){
    // map RatingBand(0..5) -> letters F..A; add S for very high.
    int b = RatingBand((double)score);                 // 0..5
    struct BV { const char* key; ImU32 color; const char* es; const char* en; };
    static const BV T[6] = {
        {"F", Col::text3,  "Desconocido",  "Unknown"},      // 0
        {"E", Col::text2,  "Novato",       "Rookie"},       // 1
        {"D", Col::text2,  "Promesa",      "Prospect"},     // 2
        {"C", Col::green,  "Competente",   "Competent"},    // 3
        {"B", Col::cyan,   "Consolidado",  "Established"},  // 4
        {"A", Col::gold,   "\xC3\x89lite", "Elite"},        // 5
    };
    if (score >= (int)bal::RATING_BAND_MIN[5] + 400) {     // "S" / Legend look
        RatingBandView v; v.idx=6; v.key="S"; v.color=Col::accent; v.es="Leyenda"; v.en="Legend"; return v;
    }
    const BV& x = T[b];
    RatingBandView v; v.idx=b; v.key=x.key; v.color=x.color; v.es=x.es; v.en=x.en; return v;
}

ProfileRatingInfo ProfileRating(int playerRating, int lastDelta){
    // Reads the persisted unified rating directly (prog.rating), with no wins/podiums anchor.
    int score = playerRating;
    ProfileRatingInfo info; info.score = score; info.band = BandView(score);
    info.delta = lastDelta;                                  // The per-race trend; no provisional badge.
    // next band threshold (for the "+N -> NextBand" hint)
    int b = info.band.idx;
    if (b >= 6) { info.next_min = 0; info.next_key = ""; }
    else if (b == 5) { info.next_min = (int)bal::RATING_BAND_MIN[5] + 400; info.next_key = "S"; info.next_es="Leyenda"; info.next_en="Legend"; }
    else {
        RatingBandView nb = BandView((int)bal::RATING_BAND_MIN[b+1] + 1);
        info.next_min = (int)bal::RATING_BAND_MIN[b+1]; info.next_key = nb.key; info.next_es = nb.es; info.next_en = nb.en;
    }
    return info;
}

std::vector<RankRow> ProfileWorldRanking(const std::map<std::string, double>& pool,
                                         const std::set<std::string>& active,
                                         const std::string& playerName, int playerRating,
                                         const std::string& /*seriesFilter*/){
    // No longer mocked: builds the board from the real driver_ratings pool, rendering only
    // the active-modern subset (`active`). Each id -> its display name via DriverById; an id with no display
    // name still renders (falls back to the id) so the board never silently drops a rated active driver — but a
    // pool id absent from `active` is skipped entirely (the historic/era and retired-driver filter).
    std::vector<RankRow> v;
    v.reserve(active.size() + 1);
    for (const auto& kv : pool) {
        const std::string& id = kv.first;
        if (id.empty()) continue;                           // unidentified entry -> skip (a defensive guard against malformed data)
        if (active.find(id) == active.end()) continue;      // not in the active-modern subset -> excluded
        // DriverDisplayName, not a raw DriverById lookup. A driver generated by the living world is not
        // in drivers.json, so this line fell back to the raw id and the world ranking would have shown the
        // player a "gn_2025_1160919266". No green test catches this: the harness compares data, it doesn't read
        // screens.
        std::string name = DriverDisplayName(id);
        int rating = (int)(kv.second + 0.5);
        RankRow row; row.name = name; row.rating = rating; row.you = false; row.band = BandView(rating);
        v.push_back(std::move(row));
    }
    // insert the player at their live rating (always present, even on an empty pool)
    { RankRow you; you.name = playerName.empty() ? std::string("Josh Bo") : playerName;
      you.rating = playerRating; you.you = true; you.band = BandView(playerRating); v.push_back(std::move(you)); }
    std::sort(v.begin(), v.end(), [](const RankRow& a, const RankRow& b){ return a.rating > b.rating; });
    return v;
}
int ProfileMyRank(const std::map<std::string, double>& pool,
                  const std::set<std::string>& active,
                  const std::string& playerName, int playerRating,
                  const std::string& seriesFilter){
    auto v = ProfileWorldRanking(pool, active, playerName, playerRating, seriesFilter);
    for (size_t i=0;i<v.size();i++) if (v[i].you) return (int)i+1;
    return (int)v.size();
}
// TU-local deterministic hash (fnv1a). Static to this TU to avoid an ODR clash with career_market.cpp /
// career_seats.cpp's own fnv1a (deterministic tie-break, no RNG).
static unsigned long profFnv1a(const std::string& s){
    unsigned long h = 2166136261UL;
    for (unsigned char c : s){ h ^= c; h *= 16777619UL; }
    return h;
}

// Pure per-id head-to-head accumulation. See career_profile.h for the
// full contract. The DNF rule is the caller's (career_overlay.cpp skips the duels when the player DNF'd, to match
// the rating model that excludes DNF — career_overlay.cpp:824); this helper is the pure positional comparison.
void AccumulateH2H(const std::vector<H2HFinish>& order, const std::string& playerId, int playerPos,
                   std::map<std::string, H2H>& h2h, const std::string& playerClass){
    if (playerPos <= 0) return;                              // player DNF/unclassified -> no duels (caller-gated too)
    for (const auto& f : order){
        if (f.driver_id.empty()) continue;                  // generic AI outside the pool -> discarded
        if (f.driver_id == playerId) continue;              // the player's own row -> excluded
        if (f.pos <= 0) continue;                            // an unclassified/DNF opponent has no comparable rank
        // Multiclass same-class gate: only compare when both classes are known and equal. An empty
        // class on either side disables the gate (single-class race compares everyone).
        if (!playerClass.empty() && !f.carClass.empty() && f.carClass != playerClass) continue;
        if (playerPos < f.pos)      h2h[f.driver_id].w++;    // player finished ahead -> a win
        else if (playerPos > f.pos) h2h[f.driver_id].l++;    // player finished behind -> a loss
        // playerPos == f.pos is impossible in a single classified finishing order (distinct ranks).
    }
}

// Real hybrid rival selection. The 3 cards = bal::RIVAL_PROXIMITY_COUNT
// (2) nearest-ELO neighbors over `activeClasses` (the proximity scope) drawn from `pool` (id->rating), plus
// 1 market rival (the seat competitor / ELO-displacement signal passed by the bridge). Selection is
// deterministic (|Δrating| sort, profFnv1a(id) tie-break — no RNG). h2h fills each card (0-0 if absent);
// the worst-balance card is flagged the nemesis once any h2h>0 exists. Display names resolve via DriverById.
//
// `activeClasses` is the bridge's proximity-scope allow-set (the union of the active-contract classes' driver ids,
// When it is non-empty it filters the pool to ids inside it; but if that scoped candidate set has fewer than
// the needed proximity count (e.g. a fresh career with no resolved class membership, or the test's class-name set),
// the filter gracefully degrades to the whole pool so the cards always populate (still deterministic).
std::vector<RivalRow> ProfileRivals(int playerRating,
                                    const std::set<std::string>& activeClasses,
                                    const std::map<std::string, double>& pool,
                                    const std::map<std::string, H2H>& h2h,
                                    const std::string& marketRivalId, int marketRivalRating,
                                    const std::string& marketRivalName){
    // a candidate = an eligible pool id + its rating + |Δ| to the player (the proximity distance).
    struct Cand { std::string id; int rating; int dist; };
    auto buildCands = [&](bool scoped)->std::vector<Cand>{
        std::vector<Cand> c;
        for (const auto& kv : pool){
            if (kv.first.empty()) continue;
            if (scoped && activeClasses.find(kv.first) == activeClasses.end()) continue;   // proximity-scope filter
            int rt = (int)(kv.second + 0.5);
            c.push_back({ kv.first, rt, std::abs(rt - playerRating) });
        }
        return c;
    };
    // Apply the proximity scope; degrade to the whole pool if the scoped set can't fill the proximity slots.
    std::vector<Cand> cands = activeClasses.empty() ? buildCands(false) : buildCands(true);
    if ((int)cands.size() < bal::RIVAL_PROXIMITY_COUNT) cands = buildCands(false);
    // nearest-ELO first; profFnv1a(id) deterministic tie-break (stable across calls, no RNG).
    std::sort(cands.begin(), cands.end(), [](const Cand& a, const Cand& b){
        if (a.dist != b.dist) return a.dist < b.dist;
        unsigned long ha = profFnv1a(a.id), hb = profFnv1a(b.id);
        if (ha != hb) return ha < hb;
        return a.id < b.id;
    });

    // build the rival id list: the top RIVAL_PROXIMITY_COUNT proximity neighbors, then the market rival.
    std::vector<std::string> ids; std::vector<int> ratings;
    for (int i = 0; i < (int)cands.size() && (int)ids.size() < bal::RIVAL_PROXIMITY_COUNT; i++){
        ids.push_back(cands[i].id); ratings.push_back(cands[i].rating);
    }
    // Market rival: the passed seat-market id. On collision with a proximity pick or an empty id, fall back
    // to the next-nearest proximity neighbor (deterministic — cands is already sorted) so the 3rd card always fills.
    bool marketUsed = false;
    if (!marketRivalId.empty()){
        bool dup = false; for (const auto& x : ids) if (x == marketRivalId) { dup = true; break; }
        if (!dup){ ids.push_back(marketRivalId); ratings.push_back(marketRivalRating); marketUsed = true; }
    }
    if (!marketUsed){
        for (int i = 0; i < (int)cands.size() && (int)ids.size() < bal::RIVAL_PROXIMITY_COUNT + 1; i++){
            bool have = false; for (const auto& x : ids) if (x == cands[i].id) { have = true; break; }
            if (!have){ ids.push_back(cands[i].id); ratings.push_back(cands[i].rating); }
        }
    }

    auto resolveName = [&](const std::string& id, const std::string& fallback)->std::string{
        // DriverDisplayName, not a raw DriverById lookup — the season-2 market rival
        // can be a driver generated by the living world (gn_*) that isn't in drivers.json, and the
        // RIVALS card was showing the player the raw id ("gn_2025_878707977"). Same pattern already patched in the
        // world ranking (above), the candidates, and the teammate.
        std::string nm = DriverDisplayName(id);
        if (nm != id) return nm;                    // pool or the generated-driver registry
        return fallback.empty() ? id : fallback;    // last resort: the name passed by the bridge, or the id
    };
    static const ImU32 kCardColors[3] = { Col::cyan, Col::amber, Col::accent };

    std::vector<RivalRow> out; out.reserve(ids.size());
    for (size_t i = 0; i < ids.size(); i++){
        const std::string& id = ids[i];
        bool isMarket = (marketUsed && i + 1 == ids.size());
        RivalRow rv;
        rv.name   = isMarket ? resolveName(id, marketRivalName) : resolveName(id, std::string());
        rv.team   = "";                                     // Residual field: real_team isn't authored here (it auto-surfaces once filled elsewhere)
        rv.rating = ratings[i];
        auto it = h2h.find(id);                             // 0-0 if absent (the card reads "—"/0–0 before any race is captured)
        rv.h2h_w = (it != h2h.end()) ? it->second.w : 0;
        rv.h2h_l = (it != h2h.end()) ? it->second.l : 0;
        rv.color = kCardColors[i < 3 ? i : 2];
        // note: proximity vs market role (bilingual; the screen renders "team · rating · note"). Nemesis is set below.
        // note_key = the stable i18n key the external UI (career_api) resolves with t() — same 4 roles.
        if (isMarket){ rv.note_es = "Rival de mercado (asiento)"; rv.note_en = "Market rival (seat)"; rv.note_key = "profile.rivalNote.market"; }
        else if (i == 0){ rv.note_es = "Vecino de ELO m\xC3\xA1s cercano"; rv.note_en = "Nearest ELO neighbor"; rv.note_key = "profile.rivalNote.nearest"; }
        else { rv.note_es = "2\xC2\xBA vecino de ELO"; rv.note_en = "2nd ELO neighbor"; rv.note_key = "profile.rivalNote.second"; }
        out.push_back(std::move(rv));
    }

    // Nemesis: the worst win-balance card once any captured h2h exists. Worst = lowest (w-l); tie -> lowest
    // win ratio w/(w+l); final tie -> profFnv1a(name) (deterministic). Flagged via the note + the accent color.
    int worst = -1; double worstBal = 1e18, worstRatio = 1e18; unsigned long worstHash = 0;
    for (size_t i = 0; i < out.size(); i++){
        const RivalRow& rv = out[i];
        if (rv.h2h_w + rv.h2h_l <= 0) continue;             // no data on this card -> not a nemesis candidate
        double bal = (double)(rv.h2h_w - rv.h2h_l);
        double ratio = (double)rv.h2h_w / (double)(rv.h2h_w + rv.h2h_l);
        unsigned long hh = profFnv1a(rv.name);
        bool better = worst < 0 || bal < worstBal
                   || (bal == worstBal && ratio < worstRatio)
                   || (bal == worstBal && ratio == worstRatio && hh < worstHash);
        if (better){ worst = (int)i; worstBal = bal; worstRatio = ratio; worstHash = hh; }
    }
    if (worst >= 0){
        out[worst].color    = Col::danger;
        out[worst].note_es  = "Tu n\xC3\xA9mesis";
        out[worst].note_en  = "Your nemesis";
        out[worst].note_key = "profile.rivalNote.nemesis";
    }
    return out;
}
// Real per-race rating arc, read over the persisted `log` (the race_log,
// already append/date-ordered: oldest first). Steps:
//  (1) OMIT every entry with rating <= 0 — the sentinel-0/legacy rows written before the rating field existed
//      plotting them would crater the chart to the floor (a fake "zero" race). After this filter every
//      kept point is a real POST-settle rating (> 0).
//  (2) DOWNSAMPLE the kept points to <= bal::ARC_DOWNSAMPLE_POINTS with an even stride that ALWAYS preserves the
//      first and last kept points — the arc's left/right endpoints stay anchored so "+N since" reads true.
//  (3) Each kept point carries a year/season label ('YY = '%02d of e.year%100).
//  (4) Append the live "Now"/"Ahora" point at `playerRating` LAST (the screen draws it as the final, highlighted
//      dot). An empty or all-legacy log returns JUST the "Now" point (no crash, no zero-spike).
// Pure: no globals, no ImGui, no I/O. Exercised by career_test::test_arc_read; fed live by ProfileRatingArcUi.
std::vector<ArcPoint> ProfileRatingArc(const std::vector<RaceLogEntry>& log, int playerRating, bool es){
    // (1) keep only real (> 0) ratings, in the log's existing date order. Build the season label here.
    std::vector<ArcPoint> kept;
    kept.reserve(log.size());
    for (const auto& e : log){
        if (e.rating <= 0) continue;                            // sentinel-0/legacy rows -> omitted (no floor-crater)
        char yy[8]; snprintf(yy, sizeof(yy), "'%02d", e.year % 100);   // year/season label ('25, '26, ...)
        ArcPoint p; p.season = yy; p.rating = e.rating;
        kept.push_back(std::move(p));
    }

    std::vector<ArcPoint> out;
    const int cap = bal::ARC_DOWNSAMPLE_POINTS;
    if ((int)kept.size() <= cap){
        out = std::move(kept);                                  // few enough -> plot them all
    } else {
        // (2) even-stride downsample that preserves the first and last kept points. Pick `cap` indices
        // spread across [0 .. last] inclusive of both ends: idx = round(i * (last) / (cap-1)) for i in 0..cap-1.
        const int last = (int)kept.size() - 1;
        out.reserve(cap);
        int prev = -1;
        for (int i = 0; i < cap; i++){
            int idx = (int)((double)i * last / (double)(cap - 1) + 0.5);
            if (idx <= prev) idx = prev + 1;                    // strictly increasing (guards rounding collisions)
            if (idx > last) idx = last;
            out.push_back(kept[idx]);
            prev = idx;
        }
        // endpoints are exact by construction (i=0 -> 0, i=cap-1 -> last), but re-assert defensively.
        out.front() = kept.front();
        out.back()  = kept.back();
    }

    // (4) append the live "Now"/"Ahora" point LAST. Always present (empty/all-legacy log -> only this point).
    out.push_back({ es ? std::string("Ahora") : std::string("Now"), playerRating });
    return out;
}

